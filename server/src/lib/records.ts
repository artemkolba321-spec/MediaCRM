import { createHash, randomUUID } from 'node:crypto';

export const COLLECTIONS = new Set([
  'channels',
  'snapshots',
  'sync_runs',
  'demographics',
  'operations',
  'partners',
  'partner_events',
  'contacts',
  'interactions',
  'segments',
  'publications',
  'publication_stats',
  'advertisers',
  'campaigns',
  'advertiser_notes',
  'campaign_documents',
  'funnels',
  'stages',
  'deals',
  'tasks',
  'notifications',
  'activity_log',
  'currency_rates',
  'settings',
]);

export const ENTITY_ID_RE = /^[A-Za-z0-9._:-]{1,64}$/;
export const MAX_PAYLOAD_BYTES = 65_536;

export function isValidCollection(value: unknown): value is string {
  return typeof value === 'string' && COLLECTIONS.has(value);
}

export function isPlainObject(value: unknown): value is Record<string, unknown> {
  return (
    typeof value === 'object' &&
    value !== null &&
    !Array.isArray(value) &&
    Object.getPrototypeOf(value) === Object.prototype
  );
}

/** 32 hex chars from a stable key. Used for deterministic server records. */
export function stableId(key: string): string {
  return createHash('sha256').update(key).digest('hex').slice(0, 32);
}

/** Deterministic UUID-shaped id for records generated by platform sync. */
export function stableUuid(key: string): string {
  const hex = createHash('sha1').update(key).digest('hex');
  const variant = ((parseInt(hex.slice(16, 18), 16) & 0x3f) | 0x80)
    .toString(16)
    .padStart(2, '0');
  return [
    hex.slice(0, 8),
    hex.slice(8, 12),
    `5${hex.slice(13, 16)}`,
    `${variant}${hex.slice(18, 20)}`,
    hex.slice(20, 32),
  ].join('-');
}

export function publicId(): string {
  return randomUUID();
}

export function isoDate(date: Date): string {
  return date.toISOString().slice(0, 10);
}

export function utcNow(): string {
  return new Date().toISOString();
}

export function daysAgo(days: number, from = new Date()): Date {
  const value = new Date(from);
  value.setUTCDate(value.getUTCDate() - days);
  return value;
}

export function safeInt(value: unknown, fallback = 0): number {
  const parsed =
    typeof value === 'number' ? value : Number.parseInt(String(value), 10);
  return Number.isFinite(parsed) ? parsed : fallback;
}

export function safeNumber(value: unknown, fallback = 0): number {
  const parsed = typeof value === 'number' ? value : Number(value);
  return Number.isFinite(parsed) ? parsed : fallback;
}
